-- 병상 상태 집계·KTAS 표시 등이 옛 값(EMPTY, '1' ...)을 못 알아본다.
-- 대상: EMERGENCY 스키마의 기존 테스트/시드 데이터. 이미 숫자인 값은 건드리지 않는다(WHERE ... IN 으로 옛 값만).
-- 실행 후 마지막 점검 쿼리에서 "옛 값이 남은 행" 이 0건이어야 한다. 실행 계정: EMERGENCY.
